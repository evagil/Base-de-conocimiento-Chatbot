import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import AttachmentPanel from './AttachmentPanel.jsx'
import { knowledgeApi } from '../api/knowledgeApi.js'
vi.mock('../api/knowledgeApi.js', () => ({ knowledgeApi: { attachments: vi.fn(), uploadAttachment: vi.fn(), updateAttachment: vi.fn(), removeAttachment: vi.fn(), attachmentContent: vi.fn() } }))
const attachment={id:1,textoAlternativo:'Manual',tipoMime:'application/pdf',tamanioBytes:512,orden:0,version:2,activo:true}
beforeEach(() => knowledgeApi.attachments.mockResolvedValue([attachment]))
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.resetAllMocks() })
it('downloads privately and hides editing controls from readers', async () => {
  knowledgeApi.attachmentContent.mockResolvedValue(new Blob(['pdf']))
  const click=vi.spyOn(HTMLAnchorElement.prototype,'click').mockImplementation(()=>{})
  render(<AttachmentPanel owner="problemas" id={3}/> )
  await screen.findByText('Manual')
  expect(screen.queryByText('Cambiar nombre')).not.toBeInTheDocument()
  expect(screen.queryByText('Adjuntar PDF o Word')).not.toBeInTheDocument()
  fireEvent.click(screen.getByText('Descargar'))
  await waitFor(()=>expect(click).toHaveBeenCalled())
  expect(knowledgeApi.attachmentContent).toHaveBeenCalledWith(1)
})
it('uploads to the selected solution and preserves a rejected upload for retry', async () => {
  knowledgeApi.attachments.mockResolvedValue([])
  knowledgeApi.uploadAttachment.mockRejectedValueOnce(new Error('No se pudo subir')).mockResolvedValueOnce(attachment)
  render(<AttachmentPanel owner="soluciones" id={7} canEdit/> )
  await waitFor(() => expect(screen.queryByText('Cargando adjuntos…')).not.toBeInTheDocument())
  const file=new File(['pdf'],'manual.pdf',{type:'application/pdf'})
  fireEvent.change(screen.getByLabelText('Seleccionar documento'),{target:{files:[file]}})
  fireEvent.click(screen.getByText('Subir archivo'))
  await screen.findByText('No se pudo subir')
  expect(screen.getByLabelText('Nombre del archivo')).toHaveValue('manual.pdf')
  fireEvent.click(screen.getByText('Subir archivo'))
  await screen.findByText('Manual')
  expect(knowledgeApi.uploadAttachment).toHaveBeenLastCalledWith('soluciones',7,file,'manual.pdf')
})
it('preserves edits on conflict and uses the updated version when deleting', async () => {
  knowledgeApi.updateAttachment.mockRejectedValueOnce(new Error('Otra persona modificó el archivo')).mockResolvedValueOnce({...attachment,textoAlternativo:'Nuevo',version:3})
  knowledgeApi.removeAttachment.mockResolvedValue({...attachment,activo:false,version:4})
  render(<AttachmentPanel owner="problemas" id={3} canEdit/> )
  fireEvent.click(await screen.findByText('Cambiar nombre'))
  fireEvent.change(screen.getByLabelText('Nombre del adjunto'),{target:{value:'Nuevo'}})
  fireEvent.click(screen.getByText('Guardar nombre'))
  await screen.findByText('Otra persona modificó el archivo')
  expect(screen.getByLabelText('Nombre del adjunto')).toHaveValue('Nuevo')
  fireEvent.click(screen.getByText('Guardar nombre'))
  await screen.findByText('Nuevo')
  expect(knowledgeApi.updateAttachment).toHaveBeenLastCalledWith(1,'Nuevo',0,2)
  const confirm=vi.spyOn(window,'confirm').mockReturnValue(false)
  fireEvent.click(screen.getByText('Eliminar adjunto'))
  expect(knowledgeApi.removeAttachment).not.toHaveBeenCalled()
  confirm.mockReturnValue(true)
  fireEvent.click(screen.getByText('Eliminar adjunto'))
  await waitFor(() => expect(screen.queryByText('Nuevo')).not.toBeInTheDocument())
  expect(knowledgeApi.removeAttachment).toHaveBeenCalledWith(1,3)
})
it('rejects unsupported formats before upload', async () => {
  render(<AttachmentPanel owner="problemas" id={3} canEdit/> )
  await screen.findByText('Manual')
  fireEvent.change(screen.getByLabelText('Seleccionar documento'),{target:{files:[new File(['x'],'x.exe')]}})
  await screen.findByText('Seleccioná un PDF o Word (.docx).')
  expect(knowledgeApi.uploadAttachment).not.toHaveBeenCalled()
})
it('keeps the last loaded attachments and distinguishes a failed refresh from an upload', async () => {
  knowledgeApi.attachments.mockResolvedValueOnce([attachment]).mockRejectedValueOnce(new Error('Network Error')).mockResolvedValueOnce([attachment])
  knowledgeApi.uploadAttachment.mockResolvedValue({...attachment,id:2,textoAlternativo:'Nuevo documento'})
  const {rerender}=render(<AttachmentPanel owner="problemas" id={3} canEdit revision={0}/>)
  await screen.findByText('Manual')
  rerender(<AttachmentPanel owner="problemas" id={3} canEdit revision={1}/>)
  await screen.findByText(/No se pudo actualizar la lista de adjuntos: Network Error/)
  expect(screen.getByText('Manual')).toBeInTheDocument()
  const file=new File(['pdf'],'nuevo.pdf',{type:'application/pdf'})
  fireEvent.change(screen.getByLabelText('Seleccionar documento'),{target:{files:[file]}})
  fireEvent.click(screen.getByText('Subir archivo'))
  await screen.findByText('Nuevo documento')
  expect(screen.getByText(/No se pudo actualizar la lista de adjuntos: Network Error/)).toBeInTheDocument()
  fireEvent.click(screen.getByText('Reintentar carga de lista'))
  await waitFor(()=>expect(screen.queryByText(/No se pudo actualizar la lista de adjuntos/)).not.toBeInTheDocument())
})

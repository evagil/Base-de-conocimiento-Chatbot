import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import ExistingImagesEditor from './ExistingImagesEditor.jsx'
import { knowledgeApi } from '../api/knowledgeApi.js'
vi.mock('../api/knowledgeApi.js', () => ({ knowledgeApi: { images: vi.fn(), updateImage: vi.fn(), removeImage: vi.fn() } }))
vi.mock('./ProtectedImage.jsx', () => ({ default: ({ image }) => <img alt={image.textoAlternativo}/> }))
const image = { id: 8, textoAlternativo: 'Captura', activo: true, orden: 3, version: 2 }
beforeEach(() => knowledgeApi.images.mockResolvedValue([image]))
afterEach(() => { cleanup(); vi.resetAllMocks() })
it('renames an image and uses the returned version for confirmed deletion', async () => {
  const onChanged = vi.fn()
  knowledgeApi.updateImage.mockResolvedValue({ ...image, textoAlternativo: 'Configuración', version: 3 })
  knowledgeApi.removeImage.mockResolvedValue({ ...image, activo: false, version: 4 })
  render(<ExistingImagesEditor owner="problemas" id={1} onChanged={onChanged}/> )
  fireEvent.change(await screen.findByLabelText('Nombre de la imagen'), { target: { value: 'Configuración' } })
  fireEvent.click(screen.getByRole('button', { name: 'Guardar nombre' }))
  await screen.findByText('Nombre guardado.')
  expect(knowledgeApi.updateImage).toHaveBeenCalledWith(8, 'Configuración', 3, 2)
  fireEvent.click(screen.getByRole('button', { name: 'Eliminar imagen' }))
  expect(knowledgeApi.removeImage).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: 'Conservar' }))
  expect(knowledgeApi.removeImage).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: 'Eliminar imagen' }))
  fireEvent.click(screen.getByRole('button', { name: 'Confirmar eliminación' }))
  await screen.findByText('No hay imágenes cargadas.')
  expect(knowledgeApi.removeImage).toHaveBeenCalledWith(8, 3)
  expect(onChanged).toHaveBeenCalledTimes(2)
})
it('retains the draft and image when a concurrent update or deletion fails', async () => {
  knowledgeApi.updateImage.mockRejectedValue(new Error('Otra persona modificó la imagen'))
  knowledgeApi.removeImage.mockRejectedValue(new Error('Otra persona modificó la imagen'))
  const onChanged = vi.fn()
  render(<ExistingImagesEditor owner="problemas" id={1} onChanged={onChanged}/> )
  fireEvent.change(await screen.findByLabelText('Nombre de la imagen'), { target: { value: 'Mi nombre pendiente' } })
  fireEvent.click(screen.getByRole('button', { name: 'Guardar nombre' }))
  await screen.findByText('Otra persona modificó la imagen')
  expect(screen.getByLabelText('Nombre de la imagen')).toHaveValue('Mi nombre pendiente')
  fireEvent.click(screen.getByRole('button', { name: 'Eliminar imagen' }))
  fireEvent.click(screen.getByRole('button', { name: 'Confirmar eliminación' }))
  await waitFor(() => expect(knowledgeApi.removeImage).toHaveBeenCalledWith(8, 2))
  await screen.findByText('Otra persona modificó la imagen')
  expect(screen.getByAltText('Captura')).toBeInTheDocument()
  expect(onChanged).not.toHaveBeenCalled()
})
it('reports loading errors and allows retry', async () => {
  knowledgeApi.images.mockRejectedValueOnce(new Error('Sin conexión'))
  render(<ExistingImagesEditor owner="problemas" id={1}/> )
  await screen.findByText('Sin conexión')
  fireEvent.click(screen.getByRole('button', { name: 'Reintentar' }))
  await screen.findByLabelText('Nombre de la imagen')
})
